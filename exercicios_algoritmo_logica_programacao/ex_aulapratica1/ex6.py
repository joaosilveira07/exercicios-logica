comp = int(input("Qual o comprimento em metros da sala? "))
larg = int(input("Qual a largura em metros da sala? "))
area = comp * larg
preco_metro = int(input("Qual o preço do metro quadrado do piso da sala"))
custo_total = area * preco_metro

print("O comprimento da sala é de: ", comp)
print("A largura da sala é de: ", larg)
print("O preço seria de: ", preco_metro)
print("O custo total para forrar o piso da sala seria de: ", custo_total)



