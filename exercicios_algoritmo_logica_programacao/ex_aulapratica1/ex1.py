num_int = int(input("Digite um número inteiro: "))
triplo_num = num_int * 3
dobro_suc = (num_int + 1) * 2

print("O triplo do seu número é: ", triplo_num)
print("O dobro do sucessor do seu número é: ", dobro_suc)
print("O resultado da diferença entre o triplo do seu número e o dobro do sucessor de seu número é: ", triplo_num - dobro_suc)
